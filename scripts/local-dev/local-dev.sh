#!/usr/bin/env bash
# Local development stack for jman: jman-api (hot reload), the web UI (Vite)
# and a jman CLI logged in to them, with all state in ./.local-dev.
#
#   local-dev.sh up            start everything; Ctrl-C stops it   (make local-dev)
#   local-dev.sh reset         delete all local state              (make local-dev-reset)
#   local-dev.sh agent-up      start the jman-agent containers     (make local-dev-agent)
#   local-dev.sh agent-down    stop them, keeping their volumes    (make local-dev-agent-down)
#   local-dev.sh infect|clean  plant or remove scan fixtures       (make local-dev-agent-infect / -clean)
#
# Nothing here reads or writes ~/.config/jman or the OS keyring, and no
# SpinupWP, Slack or PagerDuty token is configured. See README.md, "Local
# development".
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
STATE="$ROOT/.local-dev"
API_PORT="${LOCAL_DEV_API_PORT:-8080}"
UI_PORT="${LOCAL_DEV_UI_PORT:-5173}"
# localhost, not 127.0.0.1: the web UI's refresh cookie is SameSite=Strict,
# and localhost:5173 and localhost:8080 are the same site.
API_URL="http://localhost:$API_PORT"
UI_URL="http://localhost:$UI_PORT"
DEV_USER="admin"
AIR_VERSION="v1.67.4"
COMPOSE_FILE="$ROOT/scripts/local-dev/agent/compose.yaml"
COMPOSE_PROJECT="jman-local-dev"

# The agent containers: "<server name>:<site domain> <site domain> ...".
# Site users are the first label of each domain.
AGENT_SERVERS=(
	"dev-agent-1:alpha.local-dev.test beta.local-dev.test"
	"dev-agent-2:gamma.local-dev.test"
)

log() { printf '\033[1;34m[local-dev]\033[0m %s\n' "$*" >&2; }
die() { printf '\033[1;31m[local-dev]\033[0m %s\n' "$*" >&2; exit 1; }

need() {
	local cmd
	for cmd in "$@"; do
		command -v "$cmd" >/dev/null 2>&1 || die "$cmd is required but not installed"
	done
}

port_in_use() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

# Go's own caches and settings, resolved before XDG_* is pointed into
# .local-dev, so builds keep using the developer's (warm) caches.
go_env() {
	GOCACHE="$(go env GOCACHE)" GOMODCACHE="$(go env GOMODCACHE)" GOPATH="$(go env GOPATH)" GOENV="$(go env GOENV)"
	export GOCACHE GOMODCACHE GOPATH GOENV
}

# Drop any JMAN_* setting inherited from the developer's shell (a real
# SpinupWP or Slack token, say), so only what this script sets applies.
clear_jman_env() {
	local v
	for v in $(compgen -e | grep '^JMAN_' || true); do unset "$v"; done
}

# Environment of jman-api and its admin subcommands.
api_env() {
	export XDG_CONFIG_HOME="$STATE/api/config" XDG_DATA_HOME="$STATE/api/data" \
		XDG_CACHE_HOME="$STATE/api/cache" XDG_STATE_HOME="$STATE/api/state" \
		JMAN_API_PORT="$API_PORT"
}

jman_api() { (api_env; "$STATE/bin/jman-api" "$@"); }

build_binaries() {
	log "Building jman and jman-api into .local-dev/bin..."
	mkdir -p "$STATE/bin"
	(cd "$ROOT" && go build -o "$STATE/bin/jman" ./cmd/jman && go build -o "$STATE/bin/jman-api" ./cmd/jman-api)
}

write_api_config() {
	local dir="$STATE/api/config/jman"
	mkdir -p "$dir"
	chmod 700 "$STATE/api/config" "$dir"
	# Regenerated on every start; change the defaults here.
	cat >"$dir/config.toml" <<-EOF
		# Generated by scripts/local-dev/local-dev.sh on every start.
		# No SpinupWP, Slack or PagerDuty tokens: those integrations stay off.
		webUrl = "$UI_URL"
		allowedOrigins = ["$UI_URL"]
		# Uptime checks and the SpinupWP/SSH/vulnerability refresh reach real
		# hosts; both stay off locally.
		monitorDisabled = true
		refreshDisabled = true
		# The local agents collect WordPress data and scan every minute.
		agentWpDataInterval = 1
		agentScanInterval = 1
		slackChannel = ""
	EOF
	chmod 600 "$dir/config.toml"
}

ensure_user() {
	local users="$STATE/api/config/jman/users.toml" pwfile="$STATE/admin-password"
	if [[ -f "$users" && -f "$pwfile" ]]; then
		return
	fi
	[[ -f "$users" ]] && die "users.toml exists without .local-dev/admin-password; run make local-dev-reset"
	log "Creating the dev user '$DEV_USER'..."
	local pw
	pw="Dev-$(od -An -N12 -tx1 /dev/urandom | tr -d ' \n')"
	(umask 077; printf '%s\n' "$pw" >"$pwfile")
	printf '%s\n' "$pw" | jman_api useradd --username "$DEV_USER" --display-name "Local Dev Admin" --level admin --password-stdin
}

# air from PATH or GOBIN/GOPATH (like make dev-api), else a pinned go run.
air_cmd() {
	local bin
	bin="$(command -v air 2>/dev/null || true)"
	[[ -z "$bin" && -x "$(go env GOBIN)/air" ]] && bin="$(go env GOBIN)/air"
	[[ -z "$bin" && -x "$GOPATH/bin/air" ]] && bin="$GOPATH/bin/air"
	if [[ -n "$bin" ]]; then
		echo "$bin"
	else
		echo "go run github.com/air-verse/air@$AIR_VERSION"
	fi
}

wait_for() { # url seconds pid name
	local i
	for ((i = 0; i < $2; i++)); do
		curl -fsS -o /dev/null "$1" 2>/dev/null && return 0
		kill -0 "$3" 2>/dev/null || die "$4 exited during startup; see its output above"
		sleep 1
	done
	die "$4 didn't come up at $1 within $2s"
}

api_call() { # method path token [json]
	local args=(-fsS -X "$1" -H "Content-Type: application/json")
	[[ -n "$3" ]] && args+=(-H "Authorization: Bearer $3")
	[[ $# -ge 4 ]] && args+=(--data "$4")
	curl "${args[@]}" "$API_URL$2"
}

login_token() {
	api_call POST /api/auth/login "" \
		"$(jq -nc --arg u "$DEV_USER" --arg p "$(cat "$STATE/admin-password")" '{username:$u,password:$p}')" |
		jq -r .token
}

# ensure_server name ip token -> prints the server's UUID
ensure_server() {
	local id
	id="$(api_call GET '/api/servers?format=managed' "$3" | jq -r --arg n "$1" 'map(select(.name==$n))[0].id // empty')"
	if [[ -z "$id" ]]; then
		id="$(api_call POST /api/servers "$3" "$(jq -nc --arg n "$1" --arg ip "$2" '{name:$n,ip_address:$ip,provider:"manual"}')" | jq -r .id)"
	fi
	echo "$id"
}

# ensure_site token json: creates the site unless its domain exists.
ensure_site() {
	local domain
	domain="$(jq -r .domain <<<"$2")"
	if api_call GET '/api/sites?format=managed' "$1" | jq -e --arg d "$domain" 'any(.[]; .domain==$d)' >/dev/null; then
		return
	fi
	api_call POST /api/sites "$1" "$2" >/dev/null
}

# Fake servers and sites so the UI and CLI have something to show. Their
# domains (.test), SSH hosts (.invalid) and IPs (192.0.2.0/24) are reserved
# and never resolve, and with the refresh off jman-api doesn't connect to
# them on its own; a manual `jman wp` or update job just fails to resolve.
seed_fake() {
	local token="$1" web1 web2
	log "Seeding fake servers and sites..."
	web1="$(ensure_server dev-web-1 192.0.2.11 "$token")"
	web2="$(ensure_server dev-web-2 192.0.2.12 "$token")"
	local site domain server env php wp user host
	for site in \
		"shop.example.test $web1 production 8.3 true shop dev-web-1.invalid" \
		"blog.example.test $web1 production 8.2 true blog dev-web-1.invalid" \
		"staging.shop.example.test $web2 staging 8.3 true shopstaging dev-web-2.invalid" \
		"landing.example.test $web2 production 8.3 false landing dev-web-2.invalid"; do
		read -r domain server env php wp user host <<<"$site"
		ensure_site "$token" "$(jq -nc --arg d "$domain" --arg s "$server" --arg e "$env" --arg p "$php" \
			--argjson wp "$wp" --arg u "$user" --arg h "$host" \
			'{domain:$d,server_id:$s,environment:$e,php_version:$p,is_wordpress:$wp,provider:"manual",
			  connection_type:"ssh",ssh_host:$h,ssh_user:$u,can_wp_cli:$wp,has_agent:false}')"
	done
}

# Logs the CLI in without a browser: approve a PKCE challenge with the dev
# user's web session, then exchange the code like `jman login` does.
ensure_cli_login() {
	local token="$1" cfg="$STATE/cli/config/jman" creds cli_token=""
	creds="$cfg/credentials.json"
	mkdir -p "$cfg" "$STATE/cli/home"
	chmod 700 "$STATE/cli/config" "$cfg"
	if [[ -f "$creds" ]]; then
		cli_token="$(jq -r --arg u "$API_URL" '.tokens[$u] // empty' "$creds")"
		if [[ -n "$cli_token" ]] && ! api_call GET /api/user/profile "$cli_token" >/dev/null 2>&1; then
			cli_token=""
		fi
	fi
	if [[ -z "$cli_token" ]]; then
		log "Logging the local CLI in..."
		local verifier challenge code
		verifier="$(head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n')"
		challenge="$(printf '%s' "$verifier" | openssl dgst -sha256 -binary | base64 | tr '+/' '-_' | tr -d '=\n')"
		code="$(api_call POST /api/cli/authorize "$token" "$(jq -nc --arg c "$challenge" '{challenge:$c,device_name:"local-dev"}')" | jq -r .code)"
		cli_token="$(api_call POST /api/cli/token "" "$(jq -nc --arg c "$code" --arg v "$verifier" '{code:$c,verifier:$v}')" | jq -r .token)"
		(umask 077; jq -n --arg u "$API_URL" --arg t "$cli_token" '{tokens:{($u):$t}}' >"$creds")
	fi
	(umask 077; printf 'apiUrl = "%s"\n' "$API_URL" >"$cfg/config.toml")

	# The wrapper runs the CLI against .local-dev only: its own config,
	# cache and HOME, and never the OS keyring.
	cat >"$STATE/jman" <<-EOF
		#!/bin/sh
		# Generated by make local-dev: the jman CLI, logged in to the local jman-api.
		for v in \$(env | sed -n 's/^\(JMAN_[A-Za-z0-9_]*\)=.*/\1/p'); do unset "\$v"; done
		export XDG_CONFIG_HOME="$STATE/cli/config" XDG_DATA_HOME="$STATE/cli/data" \\
			XDG_CACHE_HOME="$STATE/cli/cache" XDG_STATE_HOME="$STATE/cli/state" \\
			HOME="$STATE/cli/home" JMAN_NO_KEYRING=1
		exec "$STATE/bin/jman" "\$@"
	EOF
	chmod 755 "$STATE/jman"
}

# The jman-api binary air builds and runs; it gets its own process group,
# so it is stopped by path as well in case air leaves it behind.
API_BIN() { echo "$STATE/tmp/jman-api"; }
api_running() { pgrep -f "^$(API_BIN)\$" >/dev/null 2>&1; }

PIDS=()
cleanup() {
	trap - INT TERM EXIT
	local pid i
	if ((${#PIDS[@]})); then
		log "Stopping..."
		for pid in "${PIDS[@]}"; do kill -TERM -- "-$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null || true; done
		for pid in "${PIDS[@]}"; do wait "$pid" 2>/dev/null || true; done
	fi
	pkill -TERM -f "^$(API_BIN)\$" 2>/dev/null || true
	for ((i = 0; i < 50; i++)); do api_running || return 0; sleep 0.1; done
	pkill -KILL -f "^$(API_BIN)\$" 2>/dev/null || true
}

# start name cmd... : runs cmd in its own process group with prefixed output.
start() {
	local name="$1"
	shift
	setsid "$@" > >(trap "" INT; exec sed -u "s/^/[$name] /") 2>&1 &
	PIDS+=("$!")
}

cmd_up() {
	need go pnpm curl jq openssl setsid sed od pkill
	api_running && die "a local-dev jman-api is already running ($(API_BIN))"
	port_in_use "$API_PORT" && die "port $API_PORT is in use (set LOCAL_DEV_API_PORT to use another)"
	port_in_use "$UI_PORT" && die "port $UI_PORT is in use (set LOCAL_DEV_UI_PORT to use another)"
	go_env
	clear_jman_env
	mkdir -p "$STATE"
	chmod 700 "$STATE"

	build_binaries
	write_api_config
	ensure_user

	log "Installing web UI dependencies..."
	# Run in web/: corepack picks pnpm's version from the current directory.
	(cd "$ROOT/web" && pnpm install --frozen-lockfile >/dev/null)

	trap cleanup EXIT
	trap 'exit 0' INT
	trap 'exit 143' TERM

	log "Starting jman-api with hot reload (air) on $API_URL..."
	# shellcheck disable=SC2046
	start api env XDG_CONFIG_HOME="$STATE/api/config" XDG_DATA_HOME="$STATE/api/data" \
		XDG_CACHE_HOME="$STATE/api/cache" XDG_STATE_HOME="$STATE/api/state" JMAN_API_PORT="$API_PORT" \
		bash -c 'cd "$1" && shift && exec "$@"' _ "$ROOT" $(air_cmd) -c .air.toml \
		--tmp_dir "$STATE/tmp" --build.cmd "go build -o $(API_BIN) ./cmd/jman-api" --build.bin "$(API_BIN)"
	local api_pid="${PIDS[0]}"

	log "Starting the web UI (Vite) on $UI_URL..."
	start ui env VITE_API_BASE_URL="$API_URL/api" \
		bash -c 'cd "$1" && shift && exec "$@"' _ "$ROOT/web" pnpm exec vite --port "$UI_PORT" --strictPort
	local ui_pid="${PIDS[1]}"

	wait_for "$API_URL/api/health" 180 "$api_pid" "jman-api"
	local token
	token="$(login_token)"
	seed_fake "$token"
	ensure_cli_login "$token"
	wait_for "$UI_URL/" 60 "$ui_pid" "the web UI"

	cat >&2 <<-EOF

		$(printf '\033[1;32m')jman local dev is running.$(printf '\033[0m') Ctrl-C stops it.

		  Web UI     $UI_URL
		  API        $API_URL/api
		  User       $DEV_USER
		  Password   $(cat "$STATE/admin-password")
		             (no TOTP, so admin actions are limited to edit level)
		  CLI        $STATE/jman   e.g. .local-dev/jman search example
		  State      $STATE        (make local-dev-reset wipes it)

		  Agent containers: make local-dev-agent (in another terminal)

	EOF

	# Stop everything when either process exits.
	wait -n "${PIDS[@]}" || true
	log "A process exited; shutting down."
}

cmd_reset() {
	api_running && die "make local-dev is still running; stop it (Ctrl-C) first"
	if command -v docker >/dev/null 2>&1; then
		compose down -v --remove-orphans
	fi
	rm -rf "$STATE"
	log "Removed $STATE."
}

# ---------------------------------------------------------------------------
# jman-agent containers

compose() {
	API_PORT="$API_PORT" AGENT_ENV_DIR="$STATE/agent" AGENT_BIN_DIR="$STATE/agent/bin" \
		docker compose -p "$COMPOSE_PROJECT" -f "$COMPOSE_FILE" "$@"
}

cmd_agent_up() {
	need go docker curl jq
	[[ -f "$STATE/admin-password" && -x "$STATE/bin/jman-api" ]] || die "run make local-dev first"
	curl -fsS -o /dev/null "$API_URL/api/health" 2>/dev/null || die "jman-api isn't running on $API_URL; start make local-dev first"
	go_env
	clear_jman_env
	mkdir -p "$STATE/agent/bin"
	chmod 700 "$STATE/agent"

	log "Building jman-agent for linux/$(go env GOARCH)..."
	(cd "$ROOT" && CGO_ENABLED=0 GOOS=linux go build -o "$STATE/agent/bin/jman-agent" ./cmd/jman-agent)

	local token entry server sites server_id domain
	token="$(login_token)"
	for entry in "${AGENT_SERVERS[@]}"; do
		server="${entry%%:*}"
		sites="${entry#*:}"
		server_id="$(ensure_server "$server" "" "$token")"
		for domain in $sites; do
			ensure_site "$token" "$(jq -nc --arg d "$domain" --arg s "$server_id" --arg u "${domain%%.*}" --arg h "$server.invalid" \
				'{domain:$d,server_id:$s,environment:"production",php_version:"8.4",is_wordpress:true,provider:"manual",
				  connection_type:"agent",ssh_host:$h,ssh_user:$u,can_wp_cli:true,has_agent:true}')"
		done
		if [[ ! -s "$STATE/agent/$server.env" ]]; then
			log "Creating an agent token for $server..."
			local t
			t="$(jman_api agent-token --server "$server" --description "make local-dev-agent")"
			(umask 077; printf 'JMAN_AGENT_TOKEN=%s\n' "$t" >"$STATE/agent/$server.env")
		fi
	done

	log "Starting MariaDB and the agent containers..."
	compose up -d --build --wait mariadb
	compose up -d --build
	cat >&2 <<-EOF

		The agent containers are starting. They install WordPress on first start
		(a minute or two), then report every minute.

		  Logs        docker compose -p $COMPOSE_PROJECT logs -f
		  Check WP    docker compose -p $COMPOSE_PROJECT exec dev-agent-1 jman-agent --check-wp
		  Check scan  docker compose -p $COMPOSE_PROJECT exec dev-agent-1 jman-agent --check-scan
		  Fixtures    make local-dev-agent-infect / make local-dev-agent-clean
		  Stop        make local-dev-agent-down

	EOF
}

cmd_agent_down() {
	need docker
	compose down
}

# Plants (or removes) the scan fixtures on the first agent site (alpha);
# the others stay clean for comparison.
cmd_fixtures() {
	need docker
	local entry="${AGENT_SERVERS[0]}" sites
	sites="${entry#*:}"
	compose exec -T "${entry%%:*}" local-dev-fixtures "$1" "${sites%% *}"
}

case "${1:-up}" in
up) cmd_up ;;
reset) cmd_reset ;;
agent-up) cmd_agent_up ;;
agent-down) cmd_agent_down ;;
infect) cmd_fixtures plant ;;
clean) cmd_fixtures clean ;;
*) die "usage: $0 [up|reset|agent-up|agent-down|infect|clean]" ;;
esac
